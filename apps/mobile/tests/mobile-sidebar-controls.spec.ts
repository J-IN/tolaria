import { expect, test } from '@playwright/test'

test('sidebar utility controls keep counts and open their existing surfaces', async ({ page }) => {
  await page.goto('/?source=fixture&phoneState=sidebar&tabletPanels=all')
  const sidebar = page.getByTestId('workspace-sidebar-panel')
  await expect(sidebar).toBeVisible()
  await expect(sidebar.getByTestId('sidebar-section-count-types')).toHaveCount(0)
  await expect(sidebar.getByTestId('sidebar-item-essays-count')).toBeVisible()
  const footer = sidebar.getByTestId('sidebar-settings')
  const command = footer.getByTestId('sidebar-command-palette-action')
  const settings = footer.getByTestId('open-mobile-settings')
  await expect(command).toBeVisible()
  await expect(settings).toBeVisible()
  await expect(command).toHaveCSS('border-radius', '24px')
  await expect(settings).toHaveCSS('border-radius', '24px')
  await command.click()
  await expect(page.getByTestId('mobile-command-palette')).toBeVisible()
  await page.getByTestId('mobile-command-palette-input').press('Escape')
  await expect(page.getByTestId('mobile-command-palette')).toBeHidden()
  await settings.click()
  await expect(page.getByTestId('mobile-settings')).toBeVisible()
  await page.getByLabel('Close settings', { exact: true }).click()
  await sidebar.getByTestId('sidebar-vault-picker').click()
  await expect(page.getByTestId('vault-manager')).toBeVisible()
})
